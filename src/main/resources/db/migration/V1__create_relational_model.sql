CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'DOCTOR', 'PATIENT')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_user_email_normalized CHECK (email = lower(trim(email)))
);

CREATE TABLE doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    name VARCHAR(150) NOT NULL,
    specialty VARCHAR(100) NOT NULL
);

CREATE INDEX idx_doctors_specialty ON doctors(lower(specialty));

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30)
);

CREATE TABLE doctor_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_doctor_slot UNIQUE (doctor_id, start_time),
    CONSTRAINT ck_slot_duration CHECK (end_time = start_time + INTERVAL '30 minutes'),
    CONSTRAINT ck_slot_alignment CHECK (mod(extract(epoch FROM start_time), 1800) = 0)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES doctor_slots(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('BOOKED', 'CANCELLED', 'COMPLETED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_appointments_occupied_slot ON appointments(slot_id)
    WHERE status IN ('BOOKED', 'COMPLETED');

CREATE INDEX idx_appointments_patient ON appointments(patient_id);
